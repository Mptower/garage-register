/**
 * Stages the three workspaces into addon/rootfs/app/ — the tree Supervisor
 * actually builds.
 *
 *   node scripts/build-addon.mjs           stage it
 *   node scripts/build-addon.mjs --check   fail if the stage is out of date
 *
 * Run `npm run build` first; this script only copies, it does not compile.
 *
 * Two things make this less trivial than a copy:
 *
 *  1. The staged tree is COMMITTED. Supervisor clones the repository and runs
 *     `docker build` against addon/ as-is — it never runs npm. So whatever is
 *     committed here is literally what ships.
 *
 *  2. .gitignore matches the bare names `dist` and `node_modules` at ANY depth.
 *     A staged `server/dist/...` would therefore exist on the machine that
 *     built it and be silently missing from the clone Supervisor builds — an
 *     add-on that works for you and is broken for everyone else. Every `dist`
 *     is flattened away, and assertNoIgnoredNames() refuses to finish if one
 *     survives.
 */
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STAGE = path.join(ROOT, 'addon', 'rootfs', 'app');
const CHECK = process.argv.includes('--check');

/** Names git would eat anywhere in the tree. */
const IGNORED_NAMES = new Set(['dist', 'node_modules']);

const read = (file) => fs.readFileSync(file, 'utf8');
const readJson = (file) => JSON.parse(read(file));

function fail(message) {
  console.error(`\n  build-addon: ${message}\n`);
  process.exit(1);
}

function requireDir(dir, hint) {
  if (!fs.existsSync(dir)) fail(`${path.relative(ROOT, dir)} is missing. ${hint}`);
}

/** Copy a directory's *contents* to a destination, flattening nothing else. */
function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const source = path.join(from, entry.name);
    const target = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(source, target);
    else if (entry.isFile()) fs.copyFileSync(source, target);
  }
}

function walk(dir, base = dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, base, out);
    else if (entry.isFile()) out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out;
}

const hash = (file) =>
  crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

/**
 * The reason this script exists. A surviving `dist` or `node_modules` is not a
 * tidiness problem: git drops it, and the add-on breaks only for other people.
 */
function assertNoIgnoredNames(root) {
  const offenders = [];
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      if (IGNORED_NAMES.has(entry.name)) {
        offenders.push(path.relative(ROOT, path.join(dir, entry.name)));
      }
      visit(path.join(dir, entry.name));
    }
  };
  visit(root);

  if (offenders.length > 0) {
    fail(
      `the staged tree contains directories .gitignore would drop:\n` +
        offenders.map((o) => `    ${o}`).join('\n') +
        `\n  These would be committed on this machine and missing from the clone ` +
        `Supervisor builds.`,
    );
  }
}

// ----------------------------------------------------------------- staging
function stage(destination) {
  const sharedDist = path.join(ROOT, 'shared', 'dist');
  const serverDist = path.join(ROOT, 'server', 'dist', 'src');
  const clientDist = path.join(ROOT, 'client', 'dist');

  requireDir(sharedDist, 'Run `npm run build` first.');
  requireDir(serverDist, 'Run `npm run build` first.');
  requireDir(clientDist, 'Run `npm run build` first.');

  fs.rmSync(destination, { recursive: true, force: true });
  fs.mkdirSync(destination, { recursive: true });

  // dist/ is flattened away in all three cases — see the header.
  copyDir(sharedDist, path.join(destination, 'shared'));
  copyDir(serverDist, path.join(destination, 'server'));
  copyDir(clientDist, path.join(destination, 'client'));

  // The runtime manifest for @grg/shared. The published package points at
  // dist/; the staged copy is already flattened, so it points at the root.
  fs.writeFileSync(
    path.join(destination, 'shared', 'package.json'),
    `${JSON.stringify(
      {
        name: '@grg/shared',
        private: true,
        version: '0.0.0',
        description: 'Staged runtime copy. Generated by scripts/build-addon.mjs — do not edit.',
        license: 'MIT',
        type: 'module',
        main: './index.js',
        types: './index.d.ts',
        exports: { '.': { types: './index.d.ts', default: './index.js' } },
      },
      null,
      2,
    )}\n`,
  );

  // Express is the only thing fetched from the registry. Pinned exactly so the
  // image Supervisor builds is the one that was tested, not whatever the range
  // resolves to that day.
  const serverPackage = readJson(path.join(ROOT, 'server', 'package.json'));
  const expressRange = serverPackage.dependencies.express;
  const expressPinned = resolveInstalledVersion('express', expressRange);

  fs.writeFileSync(
    path.join(destination, 'package.json'),
    `${JSON.stringify(
      {
        name: 'garage-register-addon',
        private: true,
        version: '0.0.0',
        description:
          'Production runtime for The Garage Register Home Assistant add-on. ' +
          'Generated by scripts/build-addon.mjs — do not edit.',
        license: 'MIT',
        type: 'module',
        engines: { node: '>=22.6.0' },
        dependencies: {
          '@grg/shared': 'file:shared',
          express: expressPinned,
        },
      },
      null,
      2,
    )}\n`,
  );

  return { expressPinned };
}

/** Prefer the version actually installed, so the pin matches what was tested. */
function resolveInstalledVersion(name, fallbackRange) {
  const installed = path.join(ROOT, 'node_modules', name, 'package.json');
  if (fs.existsSync(installed)) return readJson(installed).version;
  return fallbackRange.replace(/^[\^~]/, '');
}

function writeLockfile(destination) {
  // `npm ci` in the Dockerfile requires a lockfile beside the manifest.
  //
  // shell:true on Windows because Node 22 refuses to execFile a .cmd shim
  // directly (EINVAL). Every argument here is a literal, so there is nothing
  // for a shell to interpolate.
  execFileSync(
    process.platform === 'win32' ? 'npm.cmd' : 'npm',
    ['install', '--package-lock-only', '--omit=dev', '--no-audit', '--no-fund'],
    { cwd: destination, stdio: 'inherit', shell: process.platform === 'win32' },
  );
}

// ------------------------------------------------------------------- check
function check() {
  const temporary = fs.mkdtempSync(path.join(ROOT, '.addon-check-'));
  // Registered on exit rather than wrapped in try/finally: the comparison
  // below ends in process.exit when it finds a problem, which skips a finally
  // block entirely and would leave a temporary tree behind on every failed
  // run — exactly the state that made this bug visible.
  process.on('exit', () => fs.rmSync(temporary, { recursive: true, force: true }));

  stage(temporary);

  const expected = new Set(walk(temporary));
  const actual = new Set(walk(STAGE));

  // The lockfile is generated by npm and compared by its contents below,
  // not by re-resolving the registry on every CI run.
  expected.delete('package-lock.json');
  actual.delete('package-lock.json');

  const missing = [...expected].filter((f) => !actual.has(f)).sort();
  const extra = [...actual].filter((f) => !expected.has(f)).sort();
  const changed = [...expected]
    .filter((f) => actual.has(f))
    .filter((f) => hash(path.join(temporary, f)) !== hash(path.join(STAGE, f)))
    .sort();

  const problems = [];
  if (missing.length) problems.push(['missing from the stage', missing]);
  if (extra.length) problems.push(['stale in the stage', extra]);
  if (changed.length) problems.push(['out of date', changed]);

  if (!fs.existsSync(path.join(STAGE, 'package-lock.json'))) {
    problems.push(['missing', ['package-lock.json — npm ci cannot run without it']]);
  } else {
    const lock = readJson(path.join(STAGE, 'package-lock.json'));
    const staged = readJson(path.join(temporary, 'package.json')).dependencies;
    const locked = lock.packages?.['']?.dependencies ?? {};
    if (JSON.stringify(locked) !== JSON.stringify(staged)) {
      problems.push([
        'out of step with package.json',
        [`package-lock.json has ${JSON.stringify(locked)}, expected ${JSON.stringify(staged)}`],
      ]);
    }
  }

  if (problems.length > 0) {
    console.error('\n  The add-on build context is out of date.\n');
    for (const [label, files] of problems) {
      console.error(`  ${files.length} file(s) ${label}:`);
      for (const file of files.slice(0, 20)) console.error(`    ${file}`);
      if (files.length > 20) console.error(`    … and ${files.length - 20} more`);
      console.error('');
    }
    console.error('  Run `npm run build:addon` and commit the result.\n');
    process.exit(1);
  }

  assertNoIgnoredNames(STAGE);
  console.log(`  Add-on build context is up to date (${actual.size + 1} files).`);
}

// -------------------------------------------------------------------- main
if (CHECK) {
  if (!fs.existsSync(STAGE)) {
    fail('addon/rootfs/app does not exist. Run `npm run build:addon`.');
  }
  check();
} else {
  const { expressPinned } = stage(STAGE);
  writeLockfile(STAGE);
  assertNoIgnoredNames(STAGE);

  const files = walk(STAGE);
  const bytes = files.reduce((sum, f) => sum + fs.statSync(path.join(STAGE, f)).size, 0);
  const version = /^version:\s*"?([^"\s]+)"?/m.exec(
    read(path.join(ROOT, 'addon', 'config.yaml')),
  )?.[1];

  console.log(`\n  Staged addon/rootfs/app`);
  console.log(`    add-on version : ${version ?? 'unknown'}`);
  console.log(`    express        : ${expressPinned}`);
  console.log(`    files          : ${files.length}`);
  console.log(`    size           : ${(bytes / 1024 / 1024).toFixed(2)} MB`);
  console.log(`\n  Commit addon/rootfs/app so Supervisor builds what you tested.\n`);
}
